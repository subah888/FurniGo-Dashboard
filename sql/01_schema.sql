-- ---------- View: the matching rule ----------
-- A listing matches a request when the item type and area are the same,
-- the price fits the budget, and the two date windows overlap.
CREATE VIEW v_listing_matches AS
SELECT r.request_id,
       r.buyer_id,
       l.listing_id,
       l.seller_id,
       c.category_name,
       l.title,
       l.price,
       l.original_price,
       r.max_budget,
       a.city || ', ' || a.neighborhood                AS pickup_area,
       l.delivery_available,
       GREATEST(l.available_from, r.needed_from)       AS pickup_from,
       LEAST(l.available_until, r.needed_until)        AS pickup_until,
       50 + ROUND(50.0 * (r.max_budget - l.price) / NULLIF(r.max_budget, 0))::INTEGER AS match_score
FROM listings l
JOIN buyer_requests r ON r.category_id = l.category_id
                     AND r.target_area_id = l.pickup_area_id
JOIN categories c ON c.category_id = l.category_id
JOIN areas a      ON a.area_id = l.pickup_area_id
WHERE l.status = 'available'
  AND r.status = 'open'
  AND l.price <= r.max_budget
  AND l.available_from <= r.needed_until
  AND l.available_until >= r.needed_from;
