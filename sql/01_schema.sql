-- FurniGo database schema (PostgreSQL)
-- Run this file first. It drops and rebuilds every table.

DROP VIEW  IF EXISTS v_listing_matches;
DROP TABLE IF EXISTS survey_answers, survey_price_limits, survey_responses, price_bands,
                     reviews, pickup_bookings, transactions, matches, buyer_requests,
                     listings, users, areas, categories, universities CASCADE;

-- ---------- Lookup tables ----------
CREATE TABLE universities (
    university_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,
    region        TEXT NOT NULL
);

CREATE TABLE categories (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL UNIQUE
);

CREATE TABLE areas (
    area_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city         TEXT NOT NULL,
    neighborhood TEXT NOT NULL,
    UNIQUE (city, neighborhood)
);

-- ---------- Marketplace tables ----------
CREATE TABLE users (
    user_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id       INTEGER NOT NULL REFERENCES universities (university_id),
    display_name        TEXT NOT NULL,
    user_role           TEXT NOT NULL CHECK (user_role IN ('buyer', 'seller', 'both')),
    verification_status TEXT NOT NULL DEFAULT 'pending'
                        CHECK (verification_status IN ('pending', 'verified')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE listings (
    listing_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id          INTEGER NOT NULL REFERENCES users (user_id),
    category_id        INTEGER NOT NULL REFERENCES categories (category_id),
    title              TEXT NOT NULL,
    item_condition     TEXT NOT NULL CHECK (item_condition IN ('like_new', 'good', 'fair')),
    original_price     INTEGER NOT NULL CHECK (original_price >= 0),
    price              INTEGER NOT NULL CHECK (price >= 0),
    pickup_area_id     INTEGER NOT NULL REFERENCES areas (area_id),
    delivery_available BOOLEAN NOT NULL DEFAULT FALSE,
    available_from     DATE NOT NULL,
    available_until    DATE NOT NULL,   -- the seller's move-out deadline
    status             TEXT NOT NULL DEFAULT 'available'
                       CHECK (status IN ('available', 'reserved', 'sold', 'withdrawn')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (available_from <= available_until),
    CHECK (price <= original_price)
);

CREATE TABLE buyer_requests (
    request_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id       INTEGER NOT NULL REFERENCES users (user_id),
    category_id    INTEGER NOT NULL REFERENCES categories (category_id),
    max_budget     INTEGER NOT NULL CHECK (max_budget >= 0),
    target_area_id INTEGER NOT NULL REFERENCES areas (area_id),
    needed_from    DATE NOT NULL,       -- usually the buyer's move-in date
    needed_until   DATE NOT NULL,
    status         TEXT NOT NULL DEFAULT 'open'
                   CHECK (status IN ('open', 'fulfilled', 'cancelled')),
    CHECK (needed_from <= needed_until)
);

CREATE TABLE matches (
    match_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id  INTEGER NOT NULL REFERENCES listings (listing_id),
    request_id  INTEGER NOT NULL REFERENCES buyer_requests (request_id),
    match_score INTEGER NOT NULL CHECK (match_score BETWEEN 0 AND 100),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (listing_id, request_id)
);

CREATE TABLE transactions (
    transaction_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id     INTEGER NOT NULL REFERENCES listings (listing_id),
    buyer_id       INTEGER NOT NULL REFERENCES users (user_id),
    sale_price     INTEGER NOT NULL CHECK (sale_price >= 0),
    status         TEXT NOT NULL CHECK (status IN ('reserved', 'completed', 'cancelled')),
    completed_at   DATE
);

CREATE TABLE pickup_bookings (
    pickup_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  INTEGER NOT NULL REFERENCES transactions (transaction_id),
    pickup_date     DATE NOT NULL,
    delivery_option TEXT NOT NULL CHECK (delivery_option IN ('campus_pickup', 'delivery_partner')),
    delivery_fee    INTEGER NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    status          TEXT NOT NULL CHECK (status IN ('booked', 'done', 'cancelled'))
);

CREATE TABLE reviews (
    review_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id      INTEGER NOT NULL UNIQUE REFERENCES transactions (transaction_id),
    rating              INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    as_described_rating INTEGER NOT NULL CHECK (as_described_rating BETWEEN 1 AND 5),
    on_time_rating      INTEGER NOT NULL CHECK (on_time_rating BETWEEN 1 AND 5),
    comment             TEXT
);

-- ---------- Survey tables (real survey data) ----------
CREATE TABLE price_bands (
    price_band   TEXT PRIMARY KEY,
    sort_order   INTEGER NOT NULL,
    band_max_yen INTEGER            -- NULL means no upper limit
);

CREATE TABLE survey_responses (
    response_id          INTEGER PRIMARY KEY,
    submitted_at         TIMESTAMPTZ NOT NULL,
    university_id        INTEGER NOT NULL REFERENCES universities (university_id),
    living_area          TEXT,
    student_status       TEXT,
    housing_type         TEXT,
    move_date            DATE,
    travel_distance      TEXT,
    first_3m_spend       TEXT,
    difficulty_score     INTEGER CHECK (difficulty_score BETWEEN 1 AND 5),
    leaving_within_12m   TEXT,
    listing_lead_time    TEXT,
    amount_recovered     TEXT,
    satisfaction_score   INTEGER CHECK (satisfaction_score BETWEEN 1 AND 5),
    biggest_concern      TEXT,
    discount_needed      TEXT,
    delivery_fee_willing TEXT,
    pickup_fee_willing   TEXT,
    interest_score       INTEGER CHECK (interest_score BETWEEN 1 AND 5),
    payment_preference   TEXT,
    date_match_score     INTEGER CHECK (date_match_score BETWEEN 1 AND 5),
    student_only_score   INTEGER CHECK (student_only_score BETWEEN 1 AND 5),
    student_id_comfort   TEXT,
    trade_scope          TEXT,
    trust_comment        TEXT,
    other_comment        TEXT
);

-- One row per item type in the "most you would pay" grid.
CREATE TABLE survey_price_limits (
    response_id INTEGER NOT NULL REFERENCES survey_responses (response_id),
    category_id INTEGER NOT NULL REFERENCES categories (category_id),
    price_band  TEXT NOT NULL REFERENCES price_bands (price_band),
    PRIMARY KEY (response_id, category_id)
);

-- One row per ticked option in every "choose many" question.
CREATE TABLE survey_answers (
    response_id   INTEGER NOT NULL REFERENCES survey_responses (response_id),
    question_code TEXT NOT NULL,
    answer        TEXT NOT NULL,
    PRIMARY KEY (response_id, question_code, answer)
);

CREATE INDEX idx_listings_match ON listings (category_id, pickup_area_id, status);
CREATE INDEX idx_requests_match ON buyer_requests (category_id, target_area_id, status);
CREATE INDEX idx_survey_answers_q ON survey_answers (question_code);

